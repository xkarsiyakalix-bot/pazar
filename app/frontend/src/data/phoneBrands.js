export const getPhoneModels = (brandName) => {
    if (!brandName) return [];
    const brand = phoneBrands.find(
        b => b.name.toLowerCase() === String(brandName).toLowerCase() ||
             b.slug.toLowerCase() === String(brandName).toLowerCase() ||
             (b.aliases && b.aliases.some(a => a.toLowerCase() === String(brandName).toLowerCase()))
    );
    return brand ? brand.subModels : [];
};
